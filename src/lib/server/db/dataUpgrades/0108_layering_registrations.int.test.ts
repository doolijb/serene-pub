type Row = {
	scope_kind: string
	scope_ref: string
	key: string
	trigger_family: string | null
	trigger_ref: string | null
	spec_slug: string | null
	when: unknown
	values: unknown
	mode: string | null
	dropped: boolean
	origin: string
}
const regs = (scope: string, ref: string | number) =>
	rows<Row>(`SELECT * FROM registrations WHERE scope_kind = '${scope}' AND scope_ref = '${ref}' ORDER BY key`)

describe("0108 layering registrations", () => {
	it("moves bindings, toggles, configurations and tasks into registration rows", async () => {
		const report = await db.transaction(async (tx: any) => layeringUpgrade(tx, {} as any))

		// A session's event binding replaced its event's pipeline; its action
		// binding's enabled-when rides a change row; its toggle drops an
		// offered action; its tasks became routine modes and switches.
		const s100 = await regs("session", 100)
		const byKey = (list: Row[], key: string) => list.find((r) => r.key === key)
		expect(byKey(s100, "message-respond→story-respond")).toMatchObject({ dropped: true })
		expect(byKey(s100, "message-respond→acme:alt-reply")).toMatchObject({
			trigger_family: "event",
			trigger_ref: RESPOND,
			spec_slug: "acme:spec/alt-reply",
			dropped: false,
			origin: "upgrade"
		})
		expect(byKey(s100, "story-narrate#narrate→story-narrate")).toMatchObject({
			trigger_family: null,
			trigger_ref: "core:spec/story-narrate#narrate",
			when: { all: [{ on: "state.world.x", truthy: true }] }
		})
		expect(byKey(s100, "story-look#look→story-look")).toMatchObject({ dropped: true, trigger_ref: "core:spec/story-look#look" })
		expect(byKey(s100, "after-each-round→story-reckoning")).toMatchObject({
			mode: "review",
			values: { duties: { params: { attributes: true } } }
		})
		expect(byKey(s100, "on-event→story-illustrate-new-scene")).toMatchObject({ mode: "full" })
		const [fields100] = await rows<{ genre_fields: Record<string, unknown> }>(`SELECT genre_fields FROM sessions WHERE id = 100`)
		expect(fields100!.genre_fields).toEqual({ tone: "grim", sideCast: true })

		// A session's configuration became its registration's values.
		const s101 = await regs("session", 101)
		expect(byKey(s101, "message-respond→story-respond")).toMatchObject({
			trigger_family: null,
			values: { generate: { params: { maxTokens: 300 } } }
		})
		// A foreign action switched on is registered by the session.
		expect(byKey(s101, "acme:dice#roll→acme:dice")).toMatchObject({
			trigger_family: "action",
			trigger_ref: "acme:spec/dice#roll",
			spec_slug: "acme:spec/dice"
		})
		// Switched on where the preset leaves it out: registered.
		expect(byKey(await regs("session", 102), "story-look#look→story-look")).toMatchObject({ trigger_family: "action" })

		// An administrator's preset: its binding and include list as changes, its
		// configuration as values, its pinned tasks as a routine's switch.
		const p3 = await regs("preset", 3)
		expect(byKey(p3, "message-respond→story-respond")).toMatchObject({ dropped: true })
		expect(byKey(p3, "message-respond→acme:alt-reply")).toMatchObject({
			spec_slug: "acme:spec/alt-reply",
			values: { generate: { params: { maxTokens: 900 } } }
		})
		expect(p3.filter((r) => r.dropped && r.key.includes("#")).map((r) => r.key).sort()).toEqual(
			[
				"story-advance-time#advance-time→story-advance-time",
				"story-answer#answer→story-answer",
				"story-ask#ask→story-ask",
				"story-generate-image#generate-image→story-generate-image",
				"story-illustrate-scene#illustrate-scene→story-illustrate-scene",
				"story-look#look→story-look",
				"story-rest#rest→story-rest",
				"story-side-character#narrate-character→story-side-character",
				// 🚧 R50 (lane F1): the summaries' registrations are actions too, and an
				// old include list never named them — dropped with the rest (the host
				// still fires a summary; its values then come from the pipeline's
				// instance values and declared defaults).
				// 🚧 pr-6 B4: the scene summarizer's Close out (`close-out`) is a summary action too, dropped the same way.
				"story-summarize-scene#close-out→story-summarize-scene",
				"story-summarize-scene#summarize-scene→story-summarize-scene",
				"summarize-character#summarize-character→summarize-character",
				"summarize-history#summarize-history→summarize-history",
				"summarize-world#summarize-world→summarize-world"
			].sort()
		)
		expect(byKey(p3, "every-n-turns→story-sweep")).toMatchObject({
			mode: "full",
			values: { duties: { params: { summary: false } } }
		})
		const [p3Row] = await rows<{ settings: Record<string, unknown> }>(`SELECT settings FROM session_presets WHERE id = 3`)
		expect(p3Row!.settings).toEqual({ tone: "grim" })
		// Shipped presets carry no upgrade rows: the boot projects theirs.
		expect(await regs("preset", 1)).toEqual([])

		// The pub's configuration of a registered pipeline: a change to the genre's defaults.
		// 🚧 R50 (lane F1): a summary is registered too (on its summarize action,
		// in every core genre), so the pub's pick of one is carried the same way.
		expect(await regs("genre", STORY)).toEqual([
			expect.objectContaining({
				key: "admin:message-respond→story-respond",
				values: { generate: { params: { maxTokens: 500 } } },
				origin: "upgrade"
			}),
			expect.objectContaining({
				key: "admin:summarize-world#summarize-world→summarize-world",
				values: { synth: { params: { maxTokens: 50 } } },
				origin: "upgrade"
			})
		])

		// Nobody's configuration: a disabled administrator's preset of its genre.
		const [kept] = await rows<{ id: number; name: string; genre_id: string; enabled: boolean; is_immutable: boolean }>(
			`SELECT id, name, genre_id, enabled, is_immutable FROM session_presets WHERE seed_key = 'upgrade-config:13'`
		)
		expect(kept).toMatchObject({ name: "Unused", genre_id: STORY, enabled: false, is_immutable: false })
		expect(await regs("preset", kept!.id)).toEqual([
			expect.objectContaining({ key: "message-respond→story-respond", values: { reading: { params: { scene: false } } } })
		])

		// One row for the reply's pick, one per core genre for the summary's (R50).
		expect(report).toMatchObject({ pubBindingsDropped: 1, presetsFromConfigs: 1 })
		expect(report.genreRows).toBeGreaterThan(1)
		expect(report.notCarried).toEqual(expect.arrayContaining(["session #100 tasks.groups.sweep"]))
		expect(report.notCarried.some((n: string) => n.includes("configuration #14"))).toBe(false)
	}, 60_000)

	it("is idempotent", async () => {
		await db.transaction(async (tx: any) => layeringUpgrade(tx, {} as any))
		const before = await rows<{ n: number }>(`SELECT count(*)::int AS n FROM registrations`)
		const presetsBefore = await rows<{ n: number }>(`SELECT count(*)::int AS n FROM session_presets`)
		const again = await db.transaction(async (tx: any) => layeringUpgrade(tx, {} as any))
		expect(await rows(`SELECT count(*)::int AS n FROM registrations`)).toEqual(before)
		expect(await rows(`SELECT count(*)::int AS n FROM session_presets`)).toEqual(presetsBefore)
		expect(again).toMatchObject({ sessionRows: 0, presetRows: 0, genreRows: 0, presetsFromConfigs: 0 })
	}, 60_000)
})
