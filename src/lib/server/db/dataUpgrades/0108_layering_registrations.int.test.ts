/**
 * The 0108 data upgrade (PLAN-layering D7): bindings, configurations, action
 * toggles and genre tasks become registration rows. A scratch schema with
 * just the tables the upgrade reads, in today's shape, and the generated
 * migration's own `registrations` DDL — so the SQL and the mapping are what
 * is under test.
 */
import { afterEach, beforeEach, describe, expect, it } from "vitest"
import fs from "fs"
import path from "path"
import { PGlite } from "@electric-sql/pglite"
import { drizzle } from "drizzle-orm/pglite"
import { sql } from "drizzle-orm"
import { rawRows } from "../rawRows"
import { layeringUpgrade } from "./0108_layering_registrations"

let client: PGlite
let db: any

const q = (s: string) => db.execute(sql.raw(s))
const rows = async <T extends Record<string, unknown>>(s: string): Promise<T[]> => rawRows<T>(await q(s))

const STORY = "core:genre/story"
const RESPOND = "core:event/message-respond@1"
const OFFERED = "core:event/message-offered@1"

/** The generated migration's statements about `registrations`, as the anchor applies them. */
function registrationsDdl(): string[] {
	const file = path.resolve(process.cwd(), "drizzle/0108_layering_registrations.sql")
	return fs
		.readFileSync(file, "utf-8")
		.split("--> statement-breakpoint")
		.map((s) => s.trim())
		.filter((s) => s && /"registrations"/.test(s))
}

