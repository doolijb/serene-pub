/**
 * The 0151 data upgrade (variable layouts), loader and applier, on a scratch
 * schema with just the tables it reads — so the SQL is what is under test.
 * The planner's rules are in `0151_shallow_marvel_zombies.test.ts`.
 */
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest"
import { PGlite } from "@electric-sql/pglite"
import { drizzle } from "drizzle-orm/pglite"
import { sql } from "drizzle-orm"
import { rawRows } from "../rawRows"
import { run } from "./0151_shallow_marvel_zombies"

let client: PGlite
let db: any

const q = (s: string) => db.execute(sql.raw(s))
const rows = async <T extends Record<string, unknown>>(
	s: string
): Promise<T[]> => rawRows<T>(await q(s))
const upgrade = (): Promise<void> => db.transaction(async (tx: any) => run(tx))

const CHARS = "core:var/characters@1"
const PERS = "core:var/personas@1"
const seed = (v: string, variant: string) =>
	`pipeline-variable-template:${v}:${variant}`

/** Everything the upgrade may write, in a comparable shape. */
const state = async () => ({
	layouts: await rows(
		`SELECT id, pub_default FROM pipeline_variable_templates ORDER BY id`
	),
	registrations: await rows(
		`SELECT id, "values" FROM registrations ORDER BY id`
	),
	specs: await rows(
		`SELECT slug, instance_values FROM pipeline_specs ORDER BY id`
	),
	presets: await rows(
		`SELECT id, variable_layouts FROM session_presets ORDER BY id`
	)
})

beforeEach(async () => {
	client = new PGlite()
	db = drizzle(client)
	await q(`CREATE TABLE pipeline_variable_templates (id integer PRIMARY KEY, variable_id text NOT NULL, seed_key text,
		template_id text, owner_plugin_id integer, withdrawn_at timestamp, reference text, pub_default boolean NOT NULL DEFAULT false)`)
	await q(
		`CREATE TABLE pipeline_specs (id integer PRIMARY KEY, slug text NOT NULL, active_version_id integer, instance_values json)`
	)
	await q(`CREATE TABLE pipeline_nodes (id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY, spec_version_id integer NOT NULL,
		node_key text NOT NULL, definition_id text NOT NULL, definition_version integer NOT NULL DEFAULT 1,
		config json, renders json, position integer NOT NULL DEFAULT 0)`)
	await q(`CREATE TABLE pipeline_definition_registry (id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY, definition_id text NOT NULL,
		version integer NOT NULL DEFAULT 1, slots json NOT NULL DEFAULT '{}', policy jsonb)`)
	await q(
		`CREATE TABLE pipeline_presets (id integer PRIMARY KEY, spec_version_id integer NOT NULL, is_default boolean NOT NULL DEFAULT false)`
	)
	await q(`CREATE TABLE pipeline_preset_values (id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY, preset_id integer NOT NULL,
		node_key text NOT NULL, slot text NOT NULL, path text, value json)`)
	await q(`CREATE TABLE registrations (id integer PRIMARY KEY, scope_kind text NOT NULL, scope_ref text NOT NULL, preset_id integer,
		key text NOT NULL, trigger_family text, spec_slug text, "values" jsonb, dropped boolean NOT NULL DEFAULT false, origin text NOT NULL)`)
	await q(`CREATE TABLE session_presets (id integer PRIMARY KEY, genre_id text NOT NULL, seed_key text, owner_plugin_id integer,
		is_immutable boolean NOT NULL DEFAULT false, variable_layouts json NOT NULL DEFAULT '{}')`)

	await q(`INSERT INTO pipeline_variable_templates (id, variable_id, seed_key) VALUES
		(1, '${CHARS}', '${seed(CHARS, "wrapped")}'), (2, '${CHARS}', '${seed(CHARS, "content")}'), (3, '${CHARS}', NULL),
		(4, '${PERS}', '${seed(PERS, "wrapped")}'), (5, '${PERS}', '${seed(PERS, "content")}'), (6, '${PERS}', NULL)`)
	// One node definition with a variables slot rendering characters and personas; two pipelines use it.
	await q(`INSERT INTO pipeline_definition_registry (definition_id, version, slots) VALUES
		('core:task/assemble', 1, '{"variables": {"kind": "variables", "renders": {"characters": "${CHARS}", "personas": "${PERS}"}}, "template": {"kind": "template"}}')`)
	await q(
		`INSERT INTO pipeline_specs (id, slug, active_version_id) VALUES (1, 'respond', 11), (2, 'narrate', 12)`
	)
	await q(`INSERT INTO pipeline_nodes (spec_version_id, node_key, definition_id) VALUES
		(11, 'assemble', 'core:task/assemble'), (12, 'assemble', 'core:task/assemble')`)
	// The story genre registers both; an administrator's preset 50 and a shipped preset 51 exist.
	await q(
		`INSERT INTO session_presets (id, genre_id, seed_key, is_immutable) VALUES (50, 'g', NULL, false), (51, 'g', 'core:preset/x', true)`
	)
	await q(`INSERT INTO registrations (id, scope_kind, scope_ref, preset_id, key, trigger_family, spec_slug, origin) VALUES
		(1, 'genre', 'g', NULL, 'r', 'event', 'respond', 'genre'), (2, 'genre', 'g', NULL, 'n', 'event', 'narrate', 'genre')`)
}, 60_000)

afterEach(async () => {
	vi.restoreAllMocks()
	await client.close()
})

const valuesOf = async (id: number) =>
	(
		await rows<{ values: unknown }>(
			`SELECT "values" FROM registrations WHERE id = ${id}`
		)
	)[0]!.values

describe("0151: variable layouts", () => {
	it("every genre step picked one row: it becomes the pub's layout and the picks go", async () => {
		await q(`INSERT INTO registrations (id, scope_kind, scope_ref, key, spec_slug, "values", origin) VALUES
			(3, 'genre', 'g', 'admin:r', NULL, '{"assemble": {"variables": {"characters": 3}}}', 'admin'),
			(4, 'genre', 'g', 'admin:n', NULL, '{"assemble": {"variables": {"characters": 3}}}', 'admin')`)
		await upgrade()
		expect(
			(
				await rows(
					`SELECT id FROM pipeline_variable_templates WHERE pub_default`
				)
			).map((r) => r.id)
		).toEqual([3])
		expect(await valuesOf(3)).toBeNull()
		expect(await valuesOf(4)).toBeNull()
	}, 60_000)

	it("a preset whose steps all picked one core layout ends with a variable layout and no leftovers", async () => {
		await q(`INSERT INTO registrations (id, scope_kind, scope_ref, preset_id, key, spec_slug, "values", origin) VALUES
			(5, 'preset', '50', 50, 'r', NULL, '{"assemble": {"variables": {"personas": 5}}}', 'admin'),
			(6, 'preset', '50', 50, 'n', NULL, '{"assemble": {"variables": {"personas": 5}}}', 'admin')`)
		await upgrade()
		const [p] = await rows<{ variable_layouts: unknown }>(
			`SELECT variable_layouts FROM session_presets WHERE id = 50`
		)
		expect(p!.variable_layouts).toEqual({ [PERS]: "core/json@1" })
		expect(await valuesOf(5)).toBeNull()
		expect(await valuesOf(6)).toBeNull()
		expect(
			await rows(
				`SELECT id FROM pipeline_variable_templates WHERE pub_default`
			)
		).toEqual([])
	}, 60_000)

	it("one pick on one step stays, and changes nothing for the others", async () => {
		await q(`INSERT INTO registrations (id, scope_kind, scope_ref, key, spec_slug, "values", origin) VALUES
			(3, 'genre', 'g', 'admin:r', NULL, '{"assemble": {"variables": {"characters": 3}}}', 'admin')`)
		const before = await state()
		await upgrade()
		expect(await state()).toEqual(before)
	}, 60_000)

	it("instance values are swept like the others, a shipped preset's rows are not", async () => {
		await q(
			`UPDATE pipeline_specs SET instance_values = '{"assemble": {"variables": {"characters": 1}}}' WHERE slug = 'respond'`
		)
		await q(`INSERT INTO registrations (id, scope_kind, scope_ref, preset_id, key, spec_slug, "values", origin) VALUES
			(7, 'preset', '51', 51, 'r', NULL, '{"assemble": {"variables": {"characters": 2}}}', 'preset')`)
		await upgrade()
		// 1 is the default, so the instance pick is redundant; the shipped preset's row is a projection.
		expect(
			(
				await rows(
					`SELECT instance_values FROM pipeline_specs WHERE slug = 'respond'`
				)
			)[0]!.instance_values
		).toBeNull()
		expect(await valuesOf(7)).toEqual({
			assemble: { variables: { characters: 2 } }
		})
	}, 60_000)

	it("a second run changes nothing, and says nothing", async () => {
		await q(`INSERT INTO registrations (id, scope_kind, scope_ref, preset_id, key, spec_slug, "values", origin) VALUES
			(3, 'genre', 'g', NULL, 'admin:r', NULL, '{"assemble": {"variables": {"characters": 3}}}', 'admin'),
			(4, 'genre', 'g', NULL, 'admin:n', NULL, '{"assemble": {"variables": {"characters": 3}}}', 'admin'),
			(5, 'preset', '50', 50, 'r', NULL, '{"assemble": {"variables": {"personas": 5}}}', 'admin'),
			(6, 'preset', '50', 50, 'n', NULL, '{"assemble": {"variables": {"personas": 5}}}', 'admin')`)
		await upgrade()
		const first = await state()
		const log = vi.spyOn(console, "log").mockImplementation(() => {})
		await upgrade()
		expect(await state()).toEqual(first)
		expect(log).not.toHaveBeenCalled()
	}, 60_000)

	it("leaves a variable alone when its pipeline's author preset names a layout for it", async () => {
		await q(
			`INSERT INTO pipeline_presets (id, spec_version_id, is_default) VALUES (1, 12, true)`
		)
		await q(
			`INSERT INTO pipeline_preset_values (preset_id, node_key, slot, path, value) VALUES (1, 'assemble', 'variables', 'characters', '2')`
		)
		await q(`INSERT INTO registrations (id, scope_kind, scope_ref, key, spec_slug, "values", origin) VALUES
			(3, 'genre', 'g', 'admin:r', NULL, '{"assemble": {"variables": {"characters": 3}}}', 'admin'),
			(4, 'genre', 'g', 'admin:n', NULL, '{"assemble": {"variables": {"characters": 3}}}', 'admin')`)
		const before = await state()
		await upgrade()
		expect(await state()).toEqual(before)
	}, 60_000)
})
