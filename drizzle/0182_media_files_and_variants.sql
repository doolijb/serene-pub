-- Split `media` into `files` (the logical entity and its metadata) and
-- `variants` (the bytes on disk).
--
-- One `media` row per representation could not answer the question a render
-- site actually asks. Building a payload needed the original row AND a second
-- query for its thumbnail row; a thumbnail had to leave all four provenance
-- columns NULL so `mediaFor(character)` would not return it; and visibility had
-- to be written twice to keep a derivative in step. All three were symptoms of
-- one table doing two jobs.
--
-- ⚠ THERE IS NO BACKFILL, AND THAT IS A RULING RATHER THAN AN OVERSIGHT.
--
-- Test instances are recreated; prod-to-prod migration of an existing library
-- is a later, separate problem and will need its own upgrade with its own file
-- walk — the blobs on disk have to be re-stamped as `original` variants and
-- given display pointers, which is a filesystem pass and not something an
-- INSERT ... SELECT can stand in for. Dropping is the clearest honest statement
-- of that: a fresh install gets correct tables, and an existing install is told
-- plainly that its rows are gone rather than being left with a half-translated
-- library whose images render as broken.
--
-- Note the consequence for a 0.5-era instance: the 0166 data upgrade still runs
-- and still populates `media` inside 0166's own transaction, and this migration
-- then drops the result. That is the same ruling, applied to the only path that
-- could have produced rows.
--
-- CASCADE because 0166's role pointers (`characters.avatar_media_id` and
-- friends) are plain integers by ruling and hold no constraint into this table;
-- CASCADE here only takes the table's own indexes with it. Those pointers
-- survive as dangling ids, which is exactly what the no-FK ruling asks for.
DROP TABLE IF EXISTS "media" CASCADE;
