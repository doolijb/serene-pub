CREATE TABLE "files" (
	"id" integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	"uuid" uuid NOT NULL DEFAULT (gen_random_uuid ()),
	-- Cache token. Bumped only when an EXISTING variant's bytes change, or when
	-- `display_variant_id` moves. Deriving a new variant does not bump; culling
	-- one does not bump. The handler never validates the value it is sent —
	-- rejecting a stale `r` turns a stale image into a broken one.
	"rev" integer NOT NULL DEFAULT 0,
	-- Which variant a bare `/media/{uuid}` serves. A stored pointer, because a
	-- request-time size comparison would change what an already-cached
	-- immutable URL serves without changing the URL. May point at the original:
	-- a web-safe upload IS its own display form and no second copy exists.
	--
	-- No FK, and not only by the ruling above: `variants.file_id` points back,
	-- so constraints in both directions would make the first insert of either
	-- row impossible without deferring one. `cullVariant` is what keeps this
	-- pointing at a row that exists.
	"display_variant_id" integer,
	-- Denormalised from the pointed-at variant, written in the same statement.
	-- A payload must be one row.
	"display_mime" text,
	"display_bytes" integer,
	-- Provenance, and deliberately WITHOUT foreign keys (28 §2, ruled):
	-- deleting a character must leave its files behind, still stamped with that
	-- character's id, so an orphan stays groupable and attributable. A VARIANT
	-- HAS NONE OF THESE, which is what makes it structurally unreachable by a
	-- provenance query and retires the old NULL-all-four trick.
	"user_id" integer NOT NULL,
	"character_id" integer,
	"persona_id" integer,
	"session_id" integer,
	"message_id" integer,
	"visibility" text NOT NULL DEFAULT 'scoped',
	"kind" text NOT NULL,
	-- sha256 of the ORIGINAL bytes. File identity; what a re-upload matches on.
	-- Each variant carries its own hash for its own bytes: identity and an ETag
	-- are different questions, so the duplication is deliberate.
	"hash" text NOT NULL,
	"filename" text,
	"width" integer,
	"height" integer,
	-- Non-null is the signal that a time dimension exists, which is what makes
	-- a silent flatten detectable. Milliseconds; the SDK's MediaRef is seconds.
	"duration_ms" integer,
	"position" integer NOT NULL DEFAULT 0,
	"meta" json,
	"created_at" timestamp NOT NULL DEFAULT now(),
	CONSTRAINT "files_visibility_check" CHECK ("visibility" IN ('scoped', 'private'))
);
