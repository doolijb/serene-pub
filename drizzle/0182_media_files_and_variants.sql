CREATE TABLE "variants" (
	"id" integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	"file_id" integer NOT NULL,
	"variant" text NOT NULL,
	"mime" text NOT NULL,
	"bytes" integer NOT NULL,
	"path" text NOT NULL,
	"hash" text NOT NULL,
	"width" integer,
	"height" integer,
	-- The bytes the user or the backend gave us. Irreplaceable once culled.
	"is_original" boolean NOT NULL DEFAULT false,
	-- Safe to cull because it can be re-derived. FALSE on an original, and FALSE
	-- on a converted display form — the display form is not a cache entry, it is
	-- the default representation, and the cache sweep must never touch it.
	--
	-- The invariant that keeps this from destroying user data is enforced in
	-- `cullVariant`, not in the UI: never cull the last surviving representation
	-- of a file, and never cull the display target without another
	-- full-fidelity row to re-point at. "Cull originals" and "cull cache" are
	-- two clicks in either order, and only a per-call check holds for both.
	"cache" boolean NOT NULL DEFAULT false,
	-- Only `full` rows compete for the display pointer. Without this, adding one
	-- lossy transcode later would make "serve the smallest" ship degraded images
	-- to everybody, and it would look like a caching bug.
	"fidelity" text NOT NULL DEFAULT 'full',
	"created_at" timestamp NOT NULL DEFAULT now(),
	-- The variant name reaches a path builder, so it is closed here as well as
	-- validated at the route. A CHECK rather than a pg enum so adding a value
	-- later is a data change; same reasoning as `widget_styles.source`.
	CONSTRAINT "variants_variant_check" CHECK ("variant" IN ('original', 'display', 'thumb')),
	CONSTRAINT "variants_fidelity_check" CHECK ("fidelity" IN ('full', 'reduced'))
);
