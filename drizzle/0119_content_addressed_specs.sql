-- The backfill described in §3. `active_version_id` first, then the newest row
-- for the pair — an install mid-upgrade can have neither, and a run whose slug
-- and semver match nothing keeps NULL rather than borrowing another spec's hash.
UPDATE "pipeline_runs" "r"
SET "spec_hash" = (
	SELECT "v"."canonical_hash"
	FROM "pipeline_spec_versions" "v"
	JOIN "pipeline_specs" "s" ON "s"."id" = "v"."spec_id"
	WHERE "s"."slug" = "r"."spec_slug" AND "v"."semver" = "r"."spec_version"
	ORDER BY ("v"."id" = "s"."active_version_id") DESC, "v"."id" DESC
	LIMIT 1
)
WHERE "spec_hash" IS NULL;
