-- `..._seed_key_key`. Every other seeded table spells it `..._seed_key_unique`
-- (0092), and it is the name a person reads in the violation message when a
-- seed pass tries to write a key twice.
ALTER TABLE "pipeline_prompts" ADD CONSTRAINT "pipeline_prompts_seed_key_unique" UNIQUE("seed_key");--> statement-breakpoint
