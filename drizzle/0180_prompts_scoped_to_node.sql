-- ⚠ NO BACKFILL, AND THAT IS THE DECISION RATHER THAN AN OVERSIGHT.
--
-- Prompts are re-keyed from the spec to the (node type, slot) pool. Every
-- shipped row in the old table is a BUNDLE — the scene summarizer's single row
-- carries four fields belonging to four different node types — so there is no
-- row-to-row mapping to write even in principle: one row becomes four, in four
-- pools, with four new seed keys. The catalog now authors them in that shape
-- and the seed writes it on the next boot. Prod-to-prod carry-forward is a
-- separate problem, taken up later against real installs.
--
-- So do not "fix" this by adding an INSERT ... SELECT from a temp copy. There
-- is no column here that could hold the answer: which of a bundle's fields
-- belongs to which pool is a fact about the node type's declaration, which
-- lives in the registry and not in this table.
--
-- Safe to drop outright: nothing in the schema holds a foreign key INTO
-- pipeline_prompts — a config value stores the id as bare json, deliberately.
DROP TABLE IF EXISTS "pipeline_prompts" CASCADE;--> statement-breakpoint

CREATE TABLE "pipeline_prompts" (
	"id" integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	-- The pool, unversioned. Which fields a slot declares is a property of the
	-- VERSION and is checked at selection; fragmenting the pool on every
	-- @1 -> @2 would strand every prompt a user ever wrote.
	"node_type_id" text NOT NULL,
	-- The pool's second half. A type may declare more than one prompts slot
	-- with different field sets, and a prompt missing a field renders a blank —
	-- which reads as the model ignoring an instruction, not as a bad pick.
	"slot" text NOT NULL,
	-- Grouping only, never a permission, and `set null` rather than cascade:
	-- deleting a pipeline must not delete somebody's prompt.
	"created_for_spec_id" integer REFERENCES "pipeline_specs"("id") ON DELETE set null,
	-- Spec slugs whose shipped config starts on this row. A list because one
	-- pool now serves four summarize specs and the scene/history drafting
	-- prompt is ONE row belonging to two of them.
	"default_for_specs" json DEFAULT '[]'::json NOT NULL,
	-- ⚠ The spelling of these keys CHANGES (they used to embed the spec slug).
	-- seedPrompts.ts says it never may, because existing installs match rows
	-- they already wrote. That rule protects rows that exist; this statement
	-- leaves none, so the old spelling protects nothing. Deliberate, once —
	-- and the DROP above is half of the same decision. Separate them (a squash
	-- that keeps the CREATE and loses the DROP) and every install silently
	-- re-seeds 30 duplicates beside 20 orphans.
	"seed_key" text,
	"name" text NOT NULL,
	"is_immutable" boolean DEFAULT false NOT NULL,
	"fields" json DEFAULT '{}'::json NOT NULL,
	-- Text for a field the slot no longer declares. Left in `fields` it is
	-- invisible — the panel renders one box per DECLARED field — so a prompt
	-- someone spent an afternoon on becomes unfindable rather than merely
	-- unused. On the ROW so a duplicate carries it somewhere it fits again.
	"archived_fields" json DEFAULT '{}'::json NOT NULL,
	"created_at" timestamp DEFAULT now() NOT NULL,
	"updated_at" timestamp DEFAULT now() NOT NULL
);--> statement-breakpoint
